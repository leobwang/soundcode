# ─── test_demo_client_accepts_ollama_backend ───────────────────────────


def test_demo_client_accepts_ollama_backend():
    """DemoClient must construct cleanly with a real LlmServer (Ollama) as
    the backend. We pass `mistral:7b` as a stand-in model — no network
    traffic is generated by the constructor."""
    llm = LlmServer(model="mistral:7b")
    demo = DemoClient(
        llm=llm,
        checker=_FakeChecker(),
        config=DemoConfig(token_delay_s=0, repetition_window=0,
                          wall_budget_s=5),
        emit=lambda ev: asyncio.sleep(0),
    )
    assert demo.llm is llm
    assert isinstance(demo.llm, LlmServer)
    # `llm.config` must be present and a GenerationConfig — DemoClient reads
    # `.mode` off it on every generate().
    assert isinstance(demo.llm.config, GenerationConfig)


