"""Backend-switching tests: DemoClient + the BACKEND_DISPATCH / ALGORITHM_DISPATCH tables.

Covers:
  - DemoClient constructs against either backend (Ollama or vLLM)
  - BACKEND_DISPATCH produces the right type per key
  - ALGORITHM_DISPATCH maps each algorithm name to the right processor class
  - mid-session swap: closing a vLLM backend then re-loading does not leak
    state from the previous instance

Most assertions are cheap and run without GPU (we mock the vLLM engine where
needed). Only the real-load swap test is marked slow+gpu.
"""

